"""Render the registered Compass graph as deterministic Mermaid documentation.

Importing the graph builder registers nodes and routes, but it does not compile
or execute the workflow. This command therefore needs no model credential,
database, network, or custom-tool execution.
"""

from __future__ import annotations

import argparse
import io
import sys
from contextlib import redirect_stdout
from dataclasses import dataclass
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "langgraph_workflow.md"


@dataclass(frozen=True, order=True)
class WorkflowEdge:
    source: str
    target: str
    label: str = ""
    conditional: bool = False


@dataclass(frozen=True)
class WorkflowDescriptor:
    nodes: tuple[str, ...]
    edges: tuple[WorkflowEdge, ...]
    dynamic_routes: tuple[tuple[str, str], ...]


def registered_builder():
    """Import only the declarative StateGraph builder, suppressing load notices."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    with redirect_stdout(io.StringIO()):
        from agent.graph.workflow import builder

    return builder


def describe_builder(builder: Any | None = None) -> WorkflowDescriptor:
    """Return nodes and statically registered edges from a StateGraph builder."""
    graph = builder or registered_builder()
    nodes = tuple(sorted(("__start__", *graph.nodes, "__end__")))
    edges = {
        WorkflowEdge(str(source), str(target))
        for source, target in graph.edges
    }
    dynamic_routes: list[tuple[str, str]] = []
    for source, branches in graph.branches.items():
        for branch_name, branch in branches.items():
            route_name = getattr(branch.path, "name", None) or str(branch_name)
            if branch.ends:
                edges.update(
                    WorkflowEdge(
                        str(source),
                        str(target),
                        str(outcome),
                        conditional=True,
                    )
                    for outcome, target in branch.ends.items()
                )
            else:
                dynamic_routes.append((str(source), str(route_name)))
    return WorkflowDescriptor(
        nodes=nodes,
        edges=tuple(sorted(edges)),
        dynamic_routes=tuple(sorted(dynamic_routes)),
    )


def _node_id(name: str) -> str:
    return "node_" + name.strip("_").replace("-", "_")


def render_mermaid(descriptor: WorkflowDescriptor | None = None) -> str:
    """Render only graph nodes and edges present in the builder descriptor."""
    graph = descriptor or describe_builder()
    lines = ["flowchart TD"]
    for name in graph.nodes:
        node_id = _node_id(name)
        if name == "__start__":
            lines.append(f'  {node_id}(["START"])')
        elif name == "__end__":
            lines.append(f'  {node_id}(["END"])')
        else:
            lines.append(f'  {node_id}["{name}"]')
    for edge in graph.edges:
        arrow = "-.->" if edge.conditional else "-->"
        label = f"|{edge.label}|" if edge.label else ""
        lines.append(
            f"  {_node_id(edge.source)} {arrow}{label} {_node_id(edge.target)}"
        )
    return "\n".join(lines)


def render_document(descriptor: WorkflowDescriptor | None = None) -> str:
    graph = descriptor or describe_builder()
    static_edges = [edge for edge in graph.edges if not edge.conditional]
    mapped_edges = [edge for edge in graph.edges if edge.conditional]
    lines = [
        "# Compass registered workflow",
        "",
        "<!-- Generated by tools/render_workflow.py; do not edit by hand. -->",
        "",
        "This diagram is generated from the registered `StateGraph` builder without",
        "compiling or running the graph. Solid arrows are fixed edges. Dotted arrows",
        "are the executor outcomes whose destination map is registered explicitly.",
        "Other conditional routers are listed below because their destinations are",
        "chosen at runtime rather than declared as a static builder map.",
        "",
        "```mermaid",
        render_mermaid(graph),
        "```",
        "",
        "## Registered descriptor",
        "",
        f"- Nodes: {len(graph.nodes) - 2} runtime nodes, plus START and END.",
        f"- Fixed edges: {len(static_edges)}.",
        f"- Explicit conditional destinations: {len(mapped_edges)}.",
        f"- Runtime-selected conditional routers: {len(graph.dynamic_routes)}.",
        "",
        "| Conditional source | Registered route function |",
        "| --- | --- |",
    ]
    lines.extend(
        f"| `{source}` | `{route}` |" for source, route in graph.dynamic_routes
    )
    lines.extend(
        [
            "",
            "## Operational reading",
            "",
            "- Short read-only requests may enter `direct_chat` and finish without the tool loop.",
            "- Planning can pass through `planner`, `plan_approval`, and bounded read-only `coordinator` workers before `synthesis` returns to the single `executor` spine.",
            "- Tool calls pass through `check_safety`; explicit interrupts collect plan or tool approval before execution resumes.",
            "- Goal work may use linting, evaluation, limits, context injection, recovery, and threshold-based `summary_node` compaction.",
            "- Post-edit verification hooks are scheduled by the executor path, approved through the same safety boundary, and finalized before END.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--stdout", action="store_true", help="print generated Markdown")
    action.add_argument("--check", action="store_true", help="fail if the output is stale")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    rendered = render_document()
    output = args.output.resolve()
    if args.stdout:
        sys.stdout.write(rendered)
        return 0
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != rendered:
            print(f"STALE: {output}")
            return 1
        print(f"OK: {output}")
        return 0
    output.write_text(rendered, encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
